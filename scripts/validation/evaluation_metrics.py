"""Provisional exact-label metrics and separate human judgments. No provider or semantic oracle."""
from datetime import datetime
import math
import unicodedata
from typing import Literal
from pydantic import BaseModel,ConfigDict,Field,model_validator


class Strict(BaseModel):
    model_config=ConfigDict(extra='forbid',strict=True,frozen=True)


class Item(Strict):
    id:str=Field(min_length=1,max_length=200)
    text:str=Field(min_length=1,max_length=4000)
    evidence_refs:list[dict]=Field(max_length=100)


class Relation(Strict):
    source:str
    target:str
    kind:Literal['next','conditional','return','supplement','repeat']


class Labels(Strict):
    steps:list[Item]=Field(max_length=500)
    relations:list[Relation]|None=None
    deadlines:list[Item]|None=None
    conditions:list[Item]|None=None
    forms:list[Item]|None=None

    @model_validator(mode='after')
    def consistent(self):
        ids=[]
        for field in ('steps','deadlines','conditions','forms'):
            values=getattr(self,field)
            if values is not None:
                ids.extend(v.id for v in values)
                if len({normal(v.text) for v in values})!=len(values):raise ValueError('ambiguous_duplicate_label')
        if len(set(ids))!=len(ids):raise ValueError('duplicate_annotation_id')
        known={s.id for s in self.steps};edges=set()
        for e in self.relations or []:
            key=(e.source,e.target,e.kind)
            if e.source not in known or e.target not in known or key in edges:raise ValueError('invalid_annotation_edge')
            edges.add(key)
        return self


class GoldCase(Strict):
    id:str
    organization_id:str
    answer_status:Literal['answerable','abstain']
    labels:Labels
    # Only human-authored sidecar review can change this; never model output.
    human_review:Literal['PENDING_INDEPENDENT_REVIEW']='PENDING_INDEPENDENT_REVIEW'


class Pricing(Strict):
    input_rate_micro:int=Field(ge=0,le=1_000_000_000)
    output_rate_micro:int=Field(ge=0,le=1_000_000_000)
    price_version:str=Field(min_length=1,max_length=200)

    def estimate(self,input_tokens,output_tokens):
        return (input_tokens*self.input_rate_micro+output_tokens*self.output_rate_micro+999999)//1_000_000


class Prediction(Strict):
    id:str
    status:Literal['generated','retrieval_failed','generation_failed','invalid_output']
    labels:Labels
    claims:list[Item]=Field(default_factory=list,max_length=500)
    elapsed_seconds:float=Field(ge=0,allow_inf_nan=False)
    input_tokens:int|None=Field(default=None,ge=0)
    output_tokens:int|None=Field(default=None,ge=0)
    estimated_cost_micro:int|None=Field(default=None,ge=0)
    pricing:Pricing|None=None
    token_basis:Literal['NOT_MEASURED','FAKE_USAGE','PROVIDER_USAGE']='NOT_MEASURED'
    run_kind:Literal['metric_fixture','fake_model','actual_model']

    @model_validator(mode='after')
    def usage(self):
        if self.token_basis=='NOT_MEASURED' and any(x is not None for x in (self.input_tokens,self.output_tokens,self.estimated_cost_micro)):
            raise ValueError('usage_without_provenance')
        if self.token_basis!='NOT_MEASURED' and (self.input_tokens is None or self.output_tokens is None):raise ValueError('incomplete_usage')
        if self.estimated_cost_micro is not None:
            if self.pricing is None or self.input_tokens is None or self.estimated_cost_micro!=self.pricing.estimate(self.input_tokens,self.output_tokens):raise ValueError('unverified_cost_estimate')
        if len({c.id for c in self.claims})!=len(self.claims):raise ValueError('duplicate_claim_id')
        return self


class HumanReview(Strict):
    query_id:str
    reviewer:str=Field(min_length=1,max_length=200)
    reviewed_at:str
    verdict:Literal['정확','부분정확','오답','판정불가']
    reason:str=Field(min_length=1,max_length=4000)
    # Independent adjudication of each claim, not generated by scorer.
    supported_claims:int|None=Field(default=None,ge=0)
    unsupported_claims:int|None=Field(default=None,ge=0)
    @model_validator(mode='after')
    def valid(self):
        if not self.reviewer.strip() or not self.reason.strip():raise ValueError('empty_human_review')
        stamp=datetime.fromisoformat(self.reviewed_at)
        if stamp.tzinfo is None:raise ValueError('review_timezone_required')
        if (self.supported_claims is None)!=(self.unsupported_claims is None):raise ValueError('incomplete_claim_judgment')
        return self


def normal(text):return ' '.join(unicodedata.normalize('NFKC',text).split())


def prf(expected,predicted):
    expected,predicted=set(expected),set(predicted);tp=len(expected&predicted)
    p=tp/len(predicted) if predicted else None;r=tp/len(expected) if expected else None
    f=2*tp/(len(expected)+len(predicted)) if expected or predicted else None
    return {'tp':tp,'fp':len(predicted-expected),'fn':len(expected-predicted),'precision':p,'recall':r,'f1':f,
        'gold_count':len(expected),'predicted_count':len(predicted)}


def relation_keys(labels):
    ids={s.id:normal(s.text) for s in labels.steps}
    return {(ids[e.source],ids[e.target],e.kind) for e in labels.relations or []}


def invalid_gold_items(gold,resolver):
    # Wrong/foreign/unresolved proposed gold is DATA_INVALID, never an AI failure.
    bad_gold=[]
    for field in ('steps','deadlines','conditions','forms'):
        for item in getattr(gold.labels,field) or []:
            if not item.evidence_refs:bad_gold.append(item.id);continue
            for ref in item.evidence_refs:
                try:
                    if not resolver(gold.organization_id,ref)['structural_valid']:bad_gold.append(item.id)
                except Exception:bad_gold.append(item.id)
    if gold.answer_status=='answerable' and not gold.labels.steps:bad_gold.append('missing_expected_steps')
    return sorted(set(bad_gold))


def evaluate_case(gold,prediction,resolver):
    gold=GoldCase.model_validate(gold);prediction=Prediction.model_validate(prediction)
    if gold.id!=prediction.id:raise ValueError('evaluation_case_mismatch')
    bad_gold=invalid_gold_items(gold,resolver)
    if bad_gold:return {'id':gold.id,'status':'DATA_INVALID','invalid_gold_items':bad_gold,'automatic':None,'human':None}
    if prediction.status!='generated':
        return {'id':gold.id,'status':prediction.status.upper(),'automatic':None,'human':None,'excluded_from_ai_metrics':True}
    auto={}
    for field in ('steps','deadlines','conditions','forms'):
        expected=getattr(gold.labels,field);proposed=getattr(prediction.labels,field)
        auto[field]={'status':'NOT_ANNOTATED'} if expected is None else prf([normal(i.text) for i in expected],[normal(i.text) for i in proposed or []])
    for title,kinds in [('order',{'next'}),('branches',{'conditional','return','supplement','repeat'})]:
        auto[title]={'status':'NOT_ANNOTATED'} if gold.labels.relations is None else prf(
            [k for k in relation_keys(gold.labels) if k[2] in kinds],[k for k in relation_keys(prediction.labels) if k[2] in kinds])
    # Resolve all supplied citations, not just those attached to a step which happens to match.
    valid=total=unsupported=missing=0
    entries=[(i,True) for i in prediction.claims]+[(i,False) for f in ('steps','deadlines','conditions','forms') for i in getattr(prediction.labels,f) or []]
    for item,is_claim in entries:
        if not item.evidence_refs:missing+=1
        quoted=[]
        for ref in item.evidence_refs:
            total+=1
            try:
                r=resolver(gold.organization_id,ref)
                if r['structural_valid']:
                    valid+=1;quoted.extend(s['quote'] for s in r['evidence']['spans'] if s['role']=='primary')
            except Exception:pass
        if is_claim and not any(normal(item.text) in normal(t) for t in quoted):unsupported+=1
    auto['evidence_structural']={'valid':valid,'total':total,'rate':valid/total if total else None,'items_missing_evidence':missing}
    auto['unsupported_claim_proxy']={'unsupported':unsupported,'claims':len(prediction.claims),
        'rate':unsupported/len(prediction.claims) if prediction.claims else None,
        'basis':'exact normalized quote containment; NOT semantic entailment'}
    return {'id':gold.id,'status':'SCORED_PROVISIONAL','automatic':auto,'human':None,
        'semantic_accuracy':None,'approved_goldset':False,'run_kind':prediction.run_kind,
        'measurement':{'elapsed_seconds':prediction.elapsed_seconds,'input_tokens':prediction.input_tokens,
            'output_tokens':prediction.output_tokens,'estimated_cost_micro':prediction.pricing.estimate(prediction.input_tokens,prediction.output_tokens) if prediction.pricing and prediction.input_tokens is not None else None,
            'price_version':prediction.pricing.price_version if prediction.pricing else None,'token_basis':prediction.token_basis}}


def summarize(records,human_reviews=()):
    if len({r['id'] for r in records})!=len(records):raise ValueError('duplicate_scored_case')
    known={r['id'] for r in records};reviews=[HumanReview.model_validate(r) for r in human_reviews]
    if len({r.query_id for r in reviews})!=len(reviews) or any(r.query_id not in known for r in reviews):raise ValueError('unknown_or_duplicate_human_review')
    counts={s:sum(r['status']==s for r in records) for s in sorted({r['status'] for r in records})}
    rated=[r for r in reviews if r.verdict!='판정불가'];adjudicated=[r for r in reviews if r.supported_claims is not None]
    claims=sum(r.supported_claims+r.unsupported_claims for r in adjudicated)
    aggregate={}
    scored=[r['automatic'] for r in records if r.get('automatic')]
    for field in ('steps','order','branches','deadlines','conditions','forms'):
        annotated=[r[field] for r in scored if 'tp' in r[field]]
        tp=sum(r['tp'] for r in annotated);fp=sum(r['fp'] for r in annotated);fn=sum(r['fn'] for r in annotated)
        aggregate[field]={'annotated_cases':len(annotated),'not_annotated_cases':len(scored)-len(annotated),
            'tp':tp,'fp':fp,'fn':fn,'precision':tp/(tp+fp) if tp+fp else None,
            'recall':tp/(tp+fn) if tp+fn else None,'f1':2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else None,
            'exact_set_accuracy':sum(r['fp']==0 and r['fn']==0 for r in annotated)/len(annotated) if annotated else None}
    total_refs=sum(r['evidence_structural']['total'] for r in scored);valid_refs=sum(r['evidence_structural']['valid'] for r in scored)
    aggregate['evidence_structural']={'valid':valid_refs,'total':total_refs,'rate':valid_refs/total_refs if total_refs else None,
        'items_missing_evidence':sum(r['evidence_structural']['items_missing_evidence'] for r in scored)}
    total_claims=sum(r['unsupported_claim_proxy']['claims'] for r in scored);unsupported=sum(r['unsupported_claim_proxy']['unsupported'] for r in scored)
    aggregate['unsupported_claim_proxy']={'unsupported':unsupported,'claims':total_claims,'rate':unsupported/total_claims if total_claims else None,'semantic_accuracy':None}
    return {'automatic':aggregate,'case_count':len(records),'status_counts':counts,'records':records,
        'automatic_scope':'provisional exact-label/structural metrics only; generated cases denominator; all exclusions separately counted',
        'human':{'submitted_reviews':len(reviews),'pending':len(records)-len(reviews),'verdict_counts':{v:sum(r.verdict==v for r in reviews) for v in ['정확','부분정확','오답','판정불가']},
            'exact_accuracy':sum(r.verdict=='정확' for r in rated)/len(rated) if rated else None,
            'unsupported_claim_rate':sum(r.unsupported_claims for r in adjudicated)/claims if claims else None,
            'provenance':'human-supplied records only; identity/independence must be audited outside this tool'},
        'actual_ai_performance_claimed':False,'goldset_approved':False}


def proposed_gold(query):
    steps=[{'id':f"{query['id']}:step:{i}",'text':s['action'],'evidence_refs':s['evidence_refs']}
           for i,s in enumerate(query['expected_procedure'],1)]
    # Only existing explicit expected_procedure sequence is encoded, never inferred branches/deadlines/forms.
    return GoldCase(id=query['id'],organization_id=query['organization_id'],answer_status=query['answer_status'],
        labels=Labels.model_validate({'steps':steps,'relations':None,'deadlines':None,'conditions':None,'forms':None})).model_dump()
