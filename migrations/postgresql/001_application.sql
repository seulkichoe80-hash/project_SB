CREATE TABLE chunk_current(version_id TEXT PRIMARY KEY REFERENCES versions(id),job_id TEXT NOT NULL REFERENCES chunk_jobs(id));

CREATE TABLE identities(id TEXT PRIMARY KEY, issuer TEXT NOT NULL, subject TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, UNIQUE(issuer,subject));

CREATE TABLE organizations(id TEXT PRIMARY KEY, name TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);

CREATE TABLE memberships(user_id TEXT NOT NULL REFERENCES identities(id), institution_id TEXT NOT NULL REFERENCES organizations(id), role TEXT NOT NULL CHECK(role IN ('reader','manager')), active INTEGER NOT NULL DEFAULT 1, institution_admin INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(user_id,institution_id));

CREATE TABLE sessions(sid_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES identities(id), institution_id TEXT NOT NULL, csrf_hash TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL, touched DOUBLE PRECISION NOT NULL, revoked INTEGER NOT NULL DEFAULT 0);

CREATE TABLE auth_challenges(nonce_hash TEXT PRIMARY KEY, csrf_hash TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL);

CREATE TABLE auth_audit_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at DOUBLE PRECISION NOT NULL, action TEXT NOT NULL, user_id TEXT, institution_id TEXT, outcome TEXT NOT NULL);

CREATE TABLE auth_login_limits(client_hash TEXT PRIMARY KEY, "window" DOUBLE PRECISION NOT NULL, attempts INTEGER NOT NULL);

