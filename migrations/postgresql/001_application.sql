CREATE FUNCTION check_source_scope() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.version_id IS DISTINCT FROM (SELECT version_id FROM parse_jobs WHERE id=NEW.job_id)
 OR NEW.document_id IS DISTINCT FROM (SELECT document_id FROM versions WHERE id=NEW.version_id)
 THEN RAISE EXCEPTION 'source_block_scope_mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER source_block_scope BEFORE INSERT OR UPDATE ON source_blocks FOR EACH ROW EXECUTE FUNCTION check_source_scope();

CREATE FUNCTION check_chunk_scope() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.version_id IS DISTINCT FROM (SELECT version_id FROM parse_jobs WHERE id=NEW.parse_job_id)
 THEN RAISE EXCEPTION 'chunk_source_version_mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER chunk_job_scope BEFORE INSERT OR UPDATE ON chunk_jobs FOR EACH ROW EXECUTE FUNCTION check_chunk_scope();

CREATE FUNCTION check_workflow_scope() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM documents d JOIN versions v ON v.document_id=d.id
 WHERE d.id=NEW.document_id AND d.institution_id=NEW.institution_id AND v.id=NEW.version_id)
 THEN RAISE EXCEPTION 'workflow_scope_mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER workflow_job_scope BEFORE INSERT OR UPDATE ON workflow_jobs FOR EACH ROW EXECUTE FUNCTION check_workflow_scope();

CREATE FUNCTION check_active_scope() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.active_version_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM versions v WHERE v.id=NEW.active_version_id AND v.document_id=NEW.id)
 THEN RAISE EXCEPTION 'active_version_scope_mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER document_active_scope BEFORE INSERT OR UPDATE ON documents FOR EACH ROW EXECUTE FUNCTION check_active_scope();
