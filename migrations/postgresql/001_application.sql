-- Additive PostgreSQL baseline; applied once by checksum-versioned migrator.
CREATE TABLE documents (
              id TEXT PRIMARY KEY, institution_id TEXT NOT NULL,
              registered INTEGER NOT NULL DEFAULT 1, active_version_id TEXT,
              created_at TEXT NOT NULL);

CREATE TABLE versions (
              id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id),
              number INTEGER NOT NULL, original_name TEXT NOT NULL,
              size INTEGER NOT NULL, mime TEXT NOT NULL, format TEXT NOT NULL,
              sha256 TEXT NOT NULL, created_at TEXT NOT NULL, actor TEXT NOT NULL,
              state TEXT NOT NULL CHECK(state IN ('registered','queued','processing','completed','failed')),
              revision INTEGER NOT NULL DEFAULT 0, claim_hash TEXT,
              UNIQUE(document_id, number), UNIQUE(document_id,sha256));

CREATE TABLE upload_intents (
              id TEXT PRIMARY KEY, institution_id TEXT NOT NULL, status TEXT NOT NULL,
              version_id TEXT, created_at TEXT NOT NULL);

CREATE TABLE events (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version_id TEXT NOT NULL REFERENCES versions(id),
              action TEXT NOT NULL, actor TEXT NOT NULL, created_at TEXT NOT NULL);

CREATE TABLE parse_jobs (
 id TEXT PRIMARY KEY, version_id TEXT NOT NULL UNIQUE REFERENCES versions(id),
 state TEXT NOT NULL CHECK(state IN ('queued','processing','completed','failed','cancelled')),
 attempt INTEGER NOT NULL DEFAULT 0, claim_hash TEXT, lease_until DOUBLE PRECISION,
 error_code TEXT, parser_method TEXT, created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL);

CREATE TABLE parse_attempts (
 job_id TEXT NOT NULL REFERENCES parse_jobs(id), attempt INTEGER NOT NULL,
 state TEXT NOT NULL, started_at DOUBLE PRECISION NOT NULL, finished_at DOUBLE PRECISION, error_code TEXT,
 PRIMARY KEY(job_id,attempt));

CREATE TABLE source_blocks (
 job_id TEXT NOT NULL, attempt INTEGER NOT NULL, block_id TEXT NOT NULL,
 document_id TEXT NOT NULL REFERENCES documents(id), version_id TEXT NOT NULL REFERENCES versions(id),
 order_index INTEGER NOT NULL, payload TEXT NOT NULL,
 PRIMARY KEY(job_id,attempt,block_id), UNIQUE(job_id,attempt,order_index),
 FOREIGN KEY(job_id,attempt) REFERENCES parse_attempts(job_id,attempt));

CREATE TABLE schema_extensions(name TEXT PRIMARY KEY,version INTEGER NOT NULL);

CREATE TABLE chunk_jobs(
 id TEXT PRIMARY KEY,version_id TEXT NOT NULL REFERENCES versions(id),
